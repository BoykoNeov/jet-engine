def test_every_kernel_is_actually_GATED():
    """The three sets above can all agree while a kernel has NO test function calling `_check`
    on it — it would be generated, pinned, counted in the value total, and never verified. At
    eight arms that was eyeball-checkable; at twenty-six across two naming conventions it is not,
    and the failure is silent in the direction that matters (a green suite hiding an unchecked
    kernel). So read the gates' own source and assert every kernel is reached by one.

    IF THIS FAILS NAMING KERNELS YOU KNOW ARE GATED, suspect the detector before the gates.
    `inspect.getsource` re-reads THIS FILE from disk using line numbers cached at import, so
    EDITING THE FILE WHILE THE SUITE RUNS hands the regex below the wrong text and reports
    long-standing arms as ungated. Slice 4 hit exactly that: a docstring edit under a running
    gate produced '12 kernel(s) ... no test checks them' on a tree that was green. Re-run on a
    stable file before believing it — and do not edit a source file while its suite is running."""
    import inspect
    import re

    gated = set()
    for name, fn in globals().items():
        if name.startswith("test_") and callable(fn) and name != "test_every_kernel_is_actually_GATED":
            gated |= set(re.findall(r'_check\("([^"]+)"\)', inspect.getsource(fn)))
    ungated = sorted(set(KERNELS) - gated)
    assert not ungated, (
        f"{len(ungated)} kernel(s) are pinned in the golden but no test checks them: {ungated}. "
        "Add a gate — `test_golden_fingerprint_*` if the arm is <= 2 s idle, "
        "`test_golden_kernel_*` (+ `@pytest.mark.slow` if heavy) otherwise.")
    assert not (gated - set(KERNELS)), (
        f"a gate calls _check on a kernel that does not exist: {sorted(gated - set(KERNELS))}")


# --------------------------------------------------------------------------- regeneration
def _regenerate():
    """Print every changing value, THEN write. The printed diff is the point of the flag."""
    import subprocess
    import time

    try:
        old = _load_golden()["kernels"]
    except (OSError, ValueError):
        old = {}
    new = {}
    for name, fn in KERNELS.items():
        print(f"  running kernel {name} ...", flush=True)
        new[name] = {k: _encode(v) for k, v in fn().items()}

    # TWO PASSES, and the order is the whole point. A regeneration that ADDS a kernel (slice 2 of
    # the PyPy plan adds ~10) emits thousands of pure additions; a single capped list would spend
    # its budget on those and never reach a MOVED value — which is the only kind that can destroy
    # the anchor. So moved-values print FIRST and UNCAPPED; additions print after, capped.
    moved, added, removed = [], 0, []
    for name in sorted(new):
        prev, cur = old.get(name, {}), new[name]
        for k in sorted(set(prev) | set(cur)):
            if k not in prev:
                added += 1
                continue
            if k not in cur:
                removed.append(f"{name}.{k}")
                continue
            a, b = _decode(prev[k]), _decode(cur[k])
            if a != b:
                moved.append((f"{name}.{k}", a, b))
    for name in sorted(set(old) - set(new)):
        removed.extend(f"{name}.{k}" for k in sorted(old[name]))

    if moved:
        print(f"\n  !!! {len(moved)} EXISTING value(s) MOVED — this is the diff that matters:")
        for k, a, b in moved:
            print(f"    {k}\n      was {a!r}\n      now {b!r}")
    if removed:
        print(f"\n  !!! {len(removed)} value(s) DISAPPEARED (a probe's shape changed): "
              f"{removed[:10]}" + (f" ... +{len(removed) - 10}" if len(removed) > 10 else ""))
    print(f"\n  {len(moved)} moved, {len(removed)} removed, {added} newly added")
    if moved or removed:
        print("  >>> READ THAT DIFF. A MOVED or REMOVED value is the anchor changing under you.")
        print("  >>> If it is longer than you expected, STOP and work the procedure in this")
        print("  >>> module's docstring. Record in the commit message WHICH values moved, BY HOW")
        print("  >>> MUCH, and WHY that is correct.")
    else:
        print("  >>> No existing value moved. Confirm with: git diff tests/golden/ — the ONLY")
        print("  >>> '-' lines must be the `meta` block. Any other '-' line means a value moved.")

    sha = ""
    try:
        sha = subprocess.run(["git", "-C", os.path.dirname(_HERE), "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass
    if not sha:
        # SLICE 4 hit this: a BACKGROUNDED regeneration got no `git` (sandbox or the 30 s
        # timeout under load) and wrote an empty sha. Nothing was wrong with the 21 297 VALUES
        # -- only the provenance -- but the failure was silent here and only surfaced two steps
        # later in `test_golden_file_declares_its_provenance`, i.e. after the file was written.
        # Say it HERE, where the operator is still watching, so the meta block can be repaired
        # from the HEAD that was current during the run instead of re-running the 18-minute
        # regeneration for a string.
        print("  !!! WARNING: `git rev-parse HEAD` returned nothing, so `repo_sha` is EMPTY.")
        print("  !!! The values are unaffected; the PROVENANCE is not. Fill it in by hand with")
        print("  !!! the HEAD that was current during this run, or the provenance guard fails.")
    doc = {"meta": {"implementation": sys.implementation.name,
                    "version": sys.version.split()[0],
                    "generated": time.strftime("%Y-%m-%d"),
                    "repo_sha": sha,
                    "note": "CPython-generated ANCHOR. Do NOT regenerate under another "
                            "interpreter — see tests/test_numeric_fingerprint.py."},
           "kernels": new}
    os.makedirs(os.path.dirname(GOLDEN_PATH), exist_ok=True)
    # `newline=""` pins LF on Windows too. `.gitattributes` says `* text=auto eol=lf`, so a
    # CRLF write is normalised on commit and the working tree then differs from the blob --
    # which makes the NEXT regeneration's diff show every line as changed and buries the
    # "READ THAT DIFF" procedure this file rests on. Rung 77 hit the same thing on CLAUDE.md.
    with open(GOLDEN_PATH, "w", encoding="utf-8", newline="") as fh:
        json.dump(doc, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(f"  wrote {GOLDEN_PATH} "
          f"({sum(len(v) for v in new.values())} values, {os.path.getsize(GOLDEN_PATH):,} bytes)")


