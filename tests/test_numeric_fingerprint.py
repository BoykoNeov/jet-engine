def test_golden_file_declares_its_provenance():
    """The goldens' whole value is being CPython's. If the meta block ever stops saying so —
    because someone regenerated under another interpreter — the anchor is gone and this file
    silently degrades into 'the current interpreter agrees with itself'. Guard it."""
    meta = _load_golden()["meta"]
    assert meta["implementation"] == "cpython", (
        f"the golden file was generated by {meta['implementation']!r}, not CPython. "
        "Its entire value is being an INDEPENDENT anchor — see the module docstring. "
        "Restore the CPython-generated file from git; do not accept this.")
    for k in ("version", "generated", "repo_sha"):
        assert meta.get(k), f"golden meta is missing {k!r} — provenance must be complete"


def test_every_kernel_has_a_disclosed_tolerance():
    """No kernel may be compared at a tolerance that is not written down beside its measurement."""
    golden = _load_golden()
    assert set(KERNELS) == set(TOL) == set(golden["kernels"]), (
        f"kernels {sorted(KERNELS)}, tolerances {sorted(TOL)}, "
        f"goldens {sorted(golden['kernels'])} — these three sets must agree exactly")


# --------------------------------------------------------------------------- regeneration
def _regenerate():
    """Print every changing value, THEN write. The printed diff is the point of the flag."""
    import subprocess
    import time

    try:
        old = _load_golden()["kernels"]
    except (OSError, ValueError):
        old = {}
    new = {}
    for name, fn in KERNELS.items():
        print(f"  running kernel {name} ...", flush=True)
        new[name] = {k: _encode(v) for k, v in fn().items()}

    changed = 0
    for name in sorted(new):
        prev, cur = old.get(name, {}), new[name]
        for k in sorted(set(prev) | set(cur)):
            a, b = _decode(prev.get(k)) if k in prev else None, _decode(cur[k]) if k in cur else None
            if a != b:
                changed += 1
                if changed <= 40:
                    print(f"    {name}.{k}\n      was {a!r}\n      now {b!r}")
    print(f"\n  {changed} value(s) changed" + (" (first 40 shown)" if changed > 40 else ""))
    if changed:
        print("  >>> READ THAT DIFF. If it is longer than you expected, STOP and work the")
        print("  >>> procedure in this module's docstring. Record in the commit message WHICH")
        print("  >>> values moved, BY HOW MUCH, and WHY that is correct.")

    sha = ""
    try:
        sha = subprocess.run(["git", "-C", os.path.dirname(_HERE), "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=30).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass
    doc = {"meta": {"implementation": sys.implementation.name,
                    "version": sys.version.split()[0],
                    "generated": time.strftime("%Y-%m-%d"),
                    "repo_sha": sha,
                    "note": "CPython-generated ANCHOR. Do NOT regenerate under another "
                            "interpreter — see tests/test_numeric_fingerprint.py."},
           "kernels": new}
    os.makedirs(os.path.dirname(GOLDEN_PATH), exist_ok=True)
    with open(GOLDEN_PATH, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(f"  wrote {GOLDEN_PATH} "
          f"({sum(len(v) for v in new.values())} values, {os.path.getsize(GOLDEN_PATH):,} bytes)")


if __name__ == "__main__":
    if "--regenerate" in sys.argv:
        print("REGENERATING the golden fingerprint. This destroys the previous anchor.")
        _regenerate()
    else:
        for fn_name in sorted(n for n in dir() if n.startswith("test_")):
            globals()[fn_name]()
            print("ok:", fn_name)
        print("golden fingerprint: all gates pass")
