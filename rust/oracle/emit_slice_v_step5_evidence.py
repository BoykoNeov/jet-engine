# Which gates read the committed golden at all. The distinction is the whole point of a
# MANUFACTURED gate, so it is recorded per test rather than asserted in prose.
READS_GOLDEN = {
    "the_hand_built_machine_is_the_shipped_one": False,
    "the_local_armed_core_breaks_rung_57s_own_currency": True,
    "the_six_channels_of_the_plan_reproduce_live_on_both_sides": True,
    "a_constant_setting_is_the_negative_control_and_the_wrapper_did_run": False,
    "the_scoped_port_reads_a_scheduled_machine_as_an_unstatored_one": False,
    "the_remarching_reader_is_immune_and_that_is_a_call_order_property": False,
}


def run_gate():
    log = os.path.join(TMP, "step5_evidence_gate.txt")
    with io.open(log, "w", encoding="utf-8", errors="replace") as fh:
        pr = subprocess.run(["cargo", "test", "--release", "--test", "slice_v_dispatch",
                             "--", "--nocapture"],
                            cwd=RUST, stdout=fh, stderr=subprocess.STDOUT, timeout=1800)
    text = io.open(log, encoding="utf-8", errors="replace").read()
    return pr.returncode, text


def parse_channels(text):
    """The six `§ 5.20 (ii)` rows the gate prints, straight off its stdout."""
    rows = []
    pat = re.compile(r"^(\w+)\s+(\S+)\s+([\d.e+-]+) -> ([\d.e+-]+)\s+([\d.]+) %\s+"
                     r"\(miss ([\d.e+-]+) / bar (\S+)\)")
    for line in text.splitlines():
        m = pat.match(line.strip())
        if m:
            rows.append(m.groups())
    return rows


def parse_headline(text):
    m = re.search(r"^P5: margin_min_lp (\S+) -> (\S+)\s+\(([\d.]+) %\), npts (\d+) -> (\d+)",
                  text, re.M)
    return m.groups() if m else None


def parse_control(text):
    m = re.search(r"^const_lp: (\d+) wrapped calls, (\d+) of 9 readings moved", text, re.M)
    return m.groups() if m else None


def parse_counts(text):
    m = re.search(r"test result: (\w+)\. (\d+) passed; (\d+) failed; (\d+) ignored", text)
    return m.groups() if m else None


def read_table(fname):
    p = os.path.join(TMP, fname)
    if not os.path.exists(p):
        return []
    rows = []
    with io.open(p, encoding="utf-8") as fh:
        next(fh)
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 4:
                rows.append(parts)
    return rows


def main():
    rc, text = run_gate()
    channels = parse_channels(text)
    headline = parse_headline(text)
    control = parse_control(text)
    counts = parse_counts(text)
    inj = read_table("dispatch_injection_table.txt")
    self_inj = read_table("self_injection_table.txt")

    o = []
    w = o.append
    w("# Slice V step 5 — the measured evidence")
    w("")
    w("Emitted, not typed — by `rust/oracle/emit_slice_v_step5_evidence.py`, which RUNS the gate")
