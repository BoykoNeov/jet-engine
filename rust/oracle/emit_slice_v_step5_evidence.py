    w("")
    w("**How to regenerate.**")
    w("")
    w("```text")
    w(r".venv\Scripts\python.exe rust\oracle\inject_slice_v.py --dispatch")
    w(r".venv\Scripts\python.exe rust\oracle\inject_slice_v.py --self")
    w(r".venv\Scripts\python.exe rust\oracle\emit_slice_v_step5_evidence.py")
    w("```")
    w("")
    w("## 1. The gate")
    w("")
    if counts:
        w("`cargo test --release --test slice_v_dispatch` — **%s, %s passed, %s failed, "
          "%s ignored** (exit %d)." % (counts[0], counts[1], counts[2], counts[3], rc))
    w("")
    if headline:
        w("**P5, the headline.** `margin_min_lp` on the `both` arming, clean against the SAME")
        w("object with the arming scoped to the close:")
        w("")
        w("```text")
        w("clean   %s   (the committed golden `A/both/tsm/margin_min_lp`)" % headline[0])
        w("scoped  %s" % headline[1])
        w("moved   %s %%          npts %s -> %s" % (headline[2], headline[3], headline[4]))
        w("```")
        w("")
    if control:
        w("**The negative control.** `const_lp`: **%s** wrapped calls, **%s of 9** readings"
          % (control[0], control[1]))
        w("moved. A constant setting is applied by the constructor and never passes through")
        w("`_arm`, so scoping `_arm` cannot reach it — § 5.20 (ii)'s exact-zero row, live.")
        w("")
    w("## 2. § 5.20 (ii)'s six channels, both columns computed live")
    w("")
    w("| arming | key | clean | scoped | moved | miss | bar | used |")
    w("|---|---|---|---|---|---|---|---|")
    for tag, key, a, b, pct, miss, bar in channels:
        try:
            used = "%.0f %%" % (100.0 * float(miss) / float(bar))
        except (ValueError, ZeroDivisionError):
            used = "?"
        w("| `%s` | `%s` | %s | %s | %s %% | %s | %s | %s |" % (tag, key, a, b, pct, miss,
                                                                bar, used))
    w("")
    w("The clean column is asserted against `oracle/slice_v_pypy.tsv` **by key**; the scoped")
    w("column against § 5.20 (ii)'s printed value at half a unit in its own last printed place.")
    w("")
    w("## 3. The six injections against the manufactured gate")
    w("")
    w("`inject_slice_v.py --dispatch` — the step-3/4 harness with a third mode. Predictions were")
    w("written before the run; both columns are here so a wrong one cannot be quietly dropped.")
    w("")
    w("**A `MISSED` row here is not a coverage failure.** I4 (`erosion`) and I5 (the incidence")
    w("lever) are not in this file's reader chain and it builds no incidence floor — the ORACLE")
    w("covers both (14 keys and a PANIC-BEFORE-COMPARE). A carrier gate that fired on everything")
    w("would not be measuring the carrier; `const_lp`'s exact zero is the same statement from the")
    w("other side.")
    w("")
